type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
type Plural = { one: string; few?: string; many?: string; other: string };
// Translations may add few/many plural forms that English doesn't need.
type WithPlurals<T> = { [K in keyof T]: T[K] extends { one: string; other: string } ? Plural : T[K] extends string ? string : WithPlurals<T[K]> };

export type Dictionary = WithPlurals<Widen<typeof en>>;
export type PluralForms = Plural;
